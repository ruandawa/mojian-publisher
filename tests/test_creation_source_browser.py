"""Offline source-declaration state-machine fixtures, never a live receipt.

Fresh browser context, every network request blocked, temporary data store.
The complete-flow fixtures stop after the final control is clicked and never
pretend that a platform publication succeeded.
"""
import asyncio
import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import AsyncMock, Mock, patch

from playwright.async_api import async_playwright

from publisher.browser import BrowserDriver, NeedsUser
from publisher.store import Store, now


ARTICLE = {
    'title': '创作来源流程测试', 'author': '', 'digest': '', 'body': '本地测试正文',
    'format': 'markdown', 'theme': 'jade', 'cover': '', 'source': 'import',
}
REMOTE = ('https://mp.weixin.qq.com/cgi-bin/appmsg?'
          't=media/appmsg_edit_v2&action=edit&type=77&appmsgid=fixture-draft&lang=zh_CN')
REAL_SLEEP = asyncio.sleep


class FixtureStopped(RuntimeError):
    """Expected local stop; no success receipt is generated by the fixture."""


class CreationSourceBrowserTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.store = Store(Path(self.temp.name))
        self.playwright = await async_playwright().start()
        self.browser = await self.playwright.chromium.launch(channel='msedge', headless=True)
        self.context = await self.browser.new_context()
        await self.context.route('**/*', lambda route: route.abort())
        self.page = await self.context.new_page()
        self.driver = self._driver()

    def _driver(self):
        driver = BrowserDriver(self.store)
        # The browser is about:blank throughout. Only the adapter's draft URL
        # property is represented here; this cannot navigate to an account.
        page = Mock(wraps=self.page)
        page.url = REMOTE + '&token=fixture'
        driver.page = page
        driver._account = AsyncMock()
        driver._prepare_publication_receipt = AsyncMock()
        return driver

    async def asyncTearDown(self):
        await self.browser.close()
        await self.playwright.stop()
        self.temp.cleanup()

    def _job(self, creation_source='unspecified', stage='draft_saved', status='running'):
        article = self.store.save_article({**ARTICLE, 'creation_source': creation_source})
        job = self.store.enqueue(article['id'], 'publish', now())
        self.store.update_job(job['id'], stage=stage, status=status, remote_url=REMOTE)
        self.driver.page_job_id = job['id']
        return self.store.job(job['id'])

    async def _fixture(self, *, prompt_sticky=False, form_sticky=False, custom_radios=False,
                       notice_skipped=False, initial_ai=False):
        prompt = '''<div class="weui-desktop-dialog" role="dialog">
            <h2>温馨提示</h2><p>建议主动声明创作来源。如内容由AI生成，请声明。</p>
            <a href="#" onclick="enterForm();return false">去声明</a>
            <a href="#" onclick="skipSource();return false">无需声明并发表</a></div>'''
        if custom_radios:
            choices = ''.join(
                '<div role="radio" aria-checked="false" tabindex="0" '
                'onclick="choose(this,\'%s\')">%s</div>' % (value, label)
                for value, label in (
                    ('current_affairs', '涉及时事信息'), ('medical', '涉及医疗健康'),
                    ('investment', '涉及投资理财'), ('ai', '内容由AI生成'),
                    ('non_ai', '无需声明')))
        else:
            choices = ''.join(
                '<label><input type="radio" name="source" value="%s" '
                'onchange="window.flow.choices.push(this.value)">%s</label>' % (value, label)
                for value, label in (
                    ('current_affairs', '涉及时事信息'), ('medical', '涉及医疗健康'),
                    ('investment', '涉及投资理财'), ('ai', '内容由AI生成'),
                    ('non_ai', '无需声明')))
        form = ('''<div class="weui-desktop-dialog" role="dialog">
            <h2>创作来源</h2><h3>声明类型</h3><div role="radiogroup">''' + choices + '''</div>
            <button onclick="confirmSource()">确认</button>
            <button onclick="window.flow.cancel++">取消</button></div>''')
        final = '''<div class="weui-desktop-dialog" role="dialog"><h2>发表确认</h2>
            <p>请确认文章已准备好</p><a href="#" onclick="window.flow.terminal++;return false">确认发表</a>
            <button onclick="window.flow.cancel++;render('')">取消</button></div>'''
        script = '''
            window.flow = {entry:0, go:0, openSettings:0, skip:0, choices:[], sourceConfirm:0, terminal:0, cancel:0};
            window.sourceDeclared = false;
            const promptMarkup = __PROMPT__, formMarkup = __FORM__, finalMarkup = __FINAL__;
            window.render = html => document.getElementById('dialogs').innerHTML = html;
            window.showPrompt = () => {
                window.flow.entry++;
                render(__NOTICE_SKIPPED__ || window.sourceDeclared ? finalMarkup : promptMarkup);
            };
            window.enterForm = () => { window.flow.go++; render(''); };
            window.openForm = () => { window.flow.openSettings++; render(formMarkup); };
            window.skipSource = () => { window.flow.skip++; if(!__PROMPT_STICKY__) render(finalMarkup); };
            window.confirmSource = () => {
                window.flow.sourceConfirm++;
                if(!__FORM_STICKY__) {
                    window.sourceDeclared = true;
                    document.getElementById('source-value').innerText =
                        window.flow.choices.at(-1) === 'ai' ? '内容由AI生成' : '无需声明';
                    render('');
                }
            };
            window.choose = (el, value) => {
                document.querySelectorAll('[role=radio]').forEach(node=>node.setAttribute('aria-checked','false'));
                el.setAttribute('aria-checked','true'); window.flow.choices.push(value);
            };
        '''
        for old, new in (
            ('__PROMPT__', json.dumps(prompt, ensure_ascii=False)),
            ('__FORM__', json.dumps(form, ensure_ascii=False)),
            ('__FINAL__', json.dumps(final, ensure_ascii=False)),
            ('__PROMPT_STICKY__', str(prompt_sticky).lower()),
            ('__FORM_STICKY__', str(form_sticky).lower()),
            ('__NOTICE_SKIPPED__', str(notice_skipped).lower()),
        ):
            script = script.replace(old, new)
        await self.page.set_content(
            '<input id="title" value="' + ARTICLE['title'] + '">'
            '<div class="ProseMirror" contenteditable="true" data-placeholder="正文">本地正文</div>'
            '<div id="source-row"><label>创作来源</label>'
            '<button id="source-value" class="js_claim_source_selected" onclick="openForm()">'
            + ('内容由AI生成' if initial_ai else '未添加') + '</button></div>'
            '<button id="publish" onclick="showPrompt()">发表</button><div id="dialogs"></div>'
            '<script>' + script + '</script>')

    async def _flow(self):
        return await self.page.evaluate('window.flow')

    async def _run_until_action(self, job, stop_counter='terminal', settled_polls=1):
        observations = 0

        async def no_receipt():
            nonlocal observations
            flow = await self._flow()
            if flow[stop_counter]:
                observations += 1
                if observations >= settled_polls:
                    raise FixtureStopped('local fixture stopped without publication receipt')
            return False

        async def yield_only(_):
            await REAL_SLEEP(0)

        self.driver._publish_signal = no_receipt
        with patch('publisher.browser.asyncio.sleep', new=yield_only):
            with self.assertRaises(FixtureStopped):
                await self.driver._publish(job)
        self.assertNotEqual(self.store.job(job['id'])['status'], 'published')
        self.assertEqual(self.store.job(job['id'])['article_url'], '')

    async def test_unknown_source_stops_before_source_or_publication_click(self):
        await self._fixture()
        job = self._job()
        with self.assertRaisesRegex(NeedsUser, '创作来源'):
            await self.driver._publish(job)
        flow = await self._flow()
        self.assertEqual(flow['entry'], 1)
        self.assertEqual([flow[key] for key in ('go', 'skip', 'sourceConfirm', 'terminal')], [0]*4)
        self.assertEqual(flow['choices'], [])
        result = self.store.job(job['id'])
        self.assertEqual((result['stage'], result['step']), ('source_required', 'creation_source'))
        self.assertNotEqual(result['status'], 'published')


    async def test_source_required_waiting_checkpoint_reopens_original_draft_after_restart(self):
        await self._fixture(notice_skipped=True)
        job = self._job(stage='source_required', status='waiting_user')
        self.driver.page_job_id = None
        # Do not navigate: represent reopening the already loaded offline
        # editor, then let its real DOM open the prerequisite source form.
        self.driver.page.goto = AsyncMock()
        await self.driver.confirm_creation_source(job, 'non_ai')
        self.driver.page.goto.assert_awaited_once_with(
            REMOTE + '&token=fixture', wait_until='domcontentloaded')
        result = self.store.job(job['id'])
        self.assertEqual((result['status'], result['stage']), ('queued', 'draft_saved'))
        self.assertEqual(result['snapshot']['creation_source'], 'non_ai')
        self.assertEqual(result['remote_url'], REMOTE)
        flow = await self._flow()
        self.assertEqual(flow['entry'], 0)
        self.assertEqual(flow['openSettings'], 1)
        self.assertEqual([flow[key] for key in ('go', 'skip', 'sourceConfirm', 'terminal')], [0]*4)

